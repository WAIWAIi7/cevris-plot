export function englishDemo(value) {
  if (typeof value === "string") {
    if (!/[\u4e00-\u9fff]/u.test(value)) return value;
    if (Object.hasOwn(terms, value)) return terms[value];
    const match = value.match(/^([\u4e00-\u9fff]+)([A-Z0-9]+)$/u);
    if (match && terms[match[1]]) return terms[match[1]] + " " + match[2];
    throw new Error("Missing English demo text: " + value);
  }
  if (Array.isArray(value)) return value.map(englishDemo);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [englishDemo(k), englishDemo(v)]),
    );
  return value;
}
