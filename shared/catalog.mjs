export const activeParams = (id) =>
  [
    ...new Set([
      ...COMMON,
      ...(recipeById(id)?.controls || []),
      ...axisCapabilities(id).flatMap((a) => [a + "Min", a + "Max"]),
      ...(["ma", "forest"].includes(id) ? ["fillColor"] : []),
      ...(["heatmap", "correlation", "enrichment"].includes(id)
        ? ["colorLow", "colorHigh"]
        : []),
      ...(["heatmap", "correlation"].includes(id) ? ["colorMid"] : []),
    ]),
  ].filter(
    (k) =>
      !(
        ["legend", "legendGap", "legendKeySize"].includes(k) &&
        ["ma", "forest", "bland_altman", "manhattan"].includes(id)
      ),
  );
