export const chartNumber = (id) => {
  const index = NUMBERED_RECIPES.indexOf(id);
  return index < 0 ? "" : String(index + 1).padStart(3, "0");
};
// Owner-selected templates, in the requested display order (2026-11-04).
export const HOME_RECIPES = Object.freeze([
  "grouped_bar_points",
  "ribbon",
  "raincloud",
  "density",
  "circular_heatmap",
  "correlation_bubble",
  "bubble",
  "radar",
]);
export function normalizeHomeSelection(ids) {
  return Array.isArray(ids)
    ? [...new Set(ids)]
        .filter((id) => NUMBERED_RECIPES.includes(id))
        .slice(0, 24)
    : [];
}

export function resolveHomeSelection(saved) {
  // v0.7 stored plain arrays; its empty placeholder predates owner curation.
  // Versioned preferences distinguish an intentional empty home from that placeholder.
  if (saved?.version === 1 && Array.isArray(saved.ids))
    return normalizeHomeSelection(saved.ids);
  const legacy = normalizeHomeSelection(saved);
  return legacy.length ? legacy : [...HOME_RECIPES];
}
